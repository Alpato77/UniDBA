SELECT
    TABLE_NAME,
    COLUMN_ID,
    COLUMN_NAME,
    DATA_TYPE,
    DATA_LENGTH,
    DATA_PRECISION,
    DATA_SCALE,
    NULLABLE
FROM USER_TAB_COLUMNS
WHERE TABLE_NAME IN (
    'DEPARTEMENTS',
    'FILIERES',
    'ENSEIGNANTS',
    'SALLES',
    'ETUDIANTS',
    'MODULES',
    'SEANCES',
    'NOTES',
    'ABSENCES'
)
ORDER BY TABLE_NAME, COLUMN_ID;
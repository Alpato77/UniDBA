SELECT
    TABLE_NAME,
    INDEX_NAME,
    INDEX_TYPE,
    UNIQUENESS,
    STATUS
FROM USER_INDEXES
WHERE TABLE_NAME IN (
    'DEPARTEMENTS',
    'FILIERES',
    'ENSEIGNANTS',
    'SALLES',
    'ETUDIANTS',
    'MODULES',
    'SEANCES',
    'NOTES',
    'ABSENCES'
)
ORDER BY TABLE_NAME, INDEX_NAME;
SELECT
    fk.TABLE_NAME AS TABLE_ENFANT,
    fkc.COLUMN_NAME AS COLONNE_FK,
    pk.TABLE_NAME AS TABLE_PARENT,
    pkc.COLUMN_NAME AS COLONNE_PK,
    fk.CONSTRAINT_NAME AS NOM_CONTRAINTE
FROM USER_CONSTRAINTS fk
JOIN USER_CONS_COLUMNS fkc
    ON fk.CONSTRAINT_NAME = fkc.CONSTRAINT_NAME
    AND fk.TABLE_NAME = fkc.TABLE_NAME
JOIN USER_CONSTRAINTS pk
    ON fk.R_CONSTRAINT_NAME = pk.CONSTRAINT_NAME
JOIN USER_CONS_COLUMNS pkc
    ON pk.CONSTRAINT_NAME = pkc.CONSTRAINT_NAME
    AND pk.TABLE_NAME = pkc.TABLE_NAME
    AND pkc.POSITION = fkc.POSITION
WHERE fk.CONSTRAINT_TYPE = 'R'
AND fk.TABLE_NAME IN (
    'DEPARTEMENTS',
    'FILIERES',
    'ENSEIGNANTS',
    'SALLES',
    'ETUDIANTS',
    'MODULES',
    'SEANCES',
    'NOTES',
    'ABSENCES'
)
ORDER BY fk.TABLE_NAME, fk.CONSTRAINT_NAME;

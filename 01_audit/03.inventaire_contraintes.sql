SELECT
    TABLE_NAME,
    CONSTRAINT_NAME,
    CONSTRAINT_TYPE,
    STATUS,
    VALIDATED
FROM USER_CONSTRAINTS
WHERE TABLE_NAME IN (
    'DEPARTEMENTS',
    'FILIERES',
    'ENSEIGNANTS',
    'SALLES',
    'ETUDIANTS',
    'MODULES',
    'SEANCES',
    'NOTES',
    'ABSENCES'
)
ORDER BY TABLE_NAME, CONSTRAINT_TYPE;